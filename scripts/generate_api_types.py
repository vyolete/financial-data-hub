"""Generate the portal's TypeScript declarations from the approved OpenAPI document."""

import argparse
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
CONTRACT = ROOT / "specs/001-source-discovery/contracts/openapi.yaml"
OUTPUT = ROOT / "frontend/src/api/schema.d.ts"


def type_of(schema):
    if "$ref" in schema:
        return schema["$ref"].split("/")[-1]
    if "allOf" in schema:
        return " & ".join(type_of(part) for part in schema["allOf"])
    kind = schema["type"]
    if isinstance(kind, list):
        return " | ".join(type_of({**schema, "type": item}) for item in kind)
    if "enum" in schema:
        return " | ".join(repr(item) for item in schema["enum"])
    if kind == "array":
        return f"Array<{type_of(schema['items'])}>"
    if kind == "object":
        if "additionalProperties" in schema:
            return f"Record<string, {type_of(schema['additionalProperties'])}>"
        required = schema.get("required", [])
        fields = [
            f"{name}{'' if name in required else '?'}: {type_of(value)};"
            for name, value in schema["properties"].items()
        ]
        return "{ " + " ".join(fields) + " }"
    return {"integer": "number"}.get(kind, kind)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    document = yaml.safe_load(CONTRACT.read_text(encoding="utf-8"))
    components = document["components"]
    lines = ["// Generated by scripts/generate_api_types.py from the FDH-001 OpenAPI contract.", ""]
    for name, schema in components["schemas"].items():
        lines.append(f"export type {name} = {type_of(schema)};")
    lines.extend(["", "export interface Operations {"])
    for path, methods in document["paths"].items():
        operation = methods["get"]
        params = []
        for parameter in operation.get("parameters", []):
            if "$ref" in parameter:
                parameter = components["parameters"][parameter["$ref"].split("/")[-1]]
            optional = "" if parameter.get("required") else "?"
            params.append(f"{parameter['name']}{optional}: {type_of(parameter['schema'])};")
        parameters = "{ " + " ".join(params) + " }" if params else "Record<string, never>"
        response = type_of(operation["responses"]["200"]["content"]["application/json"]["schema"])
        lines.append(
            f"  {operation['operationId']}: {{ path: {path!r}; "
            f"params: {parameters}; result: {response} }};"
        )
    lines.extend(["}", ""])
    content = "\n".join(lines)
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != content:
            parser.exit(1, "Portal OpenAPI types are out of date. Run scripts/generate_api_types.py.\n")
    else:
        OUTPUT.write_text(content, encoding="utf-8")


if __name__ == "__main__":
    main()
